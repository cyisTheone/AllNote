"""
题目描述在进行信道资源分配时，需要通过掩码（Bitmask）来高效管理可用信道的状态。每个信道对应掩码中的一个二进制位，该位为 1 表示信道可用，为 0 表示信道被占用。掩码状态编码以不同进制格式（二进制、十进制、十六进制）存储在配置文件中，由 64 位无符号整数表示，二进制从低位到高位对应信道 0 到信道 63。掩码的输入格式为带进制标识的字符串。二进制字符串以 0b 开头，如 0b1011；十六进制字符串以 0x 开头，如 0x1A3；十进制字符串无特殊前缀，如 255。为了优化资源利用率，需计算两组可用信道的集合：交集、并集，以及统计连续可用信道的最大长度（连续 1 的最长子串）。请实现一个函数完成以下操作：
将两个输入的掩码字符串（maskStrA、maskStrB）转为 64 位无符号整数；
计算两个掩码的可用信道交集（仅保留两个掩码中都为 1 的位）；
计算两个掩码的可用信道并集（保留任意一个掩码中为 1 的位）；
统计两个掩码的连续可用信道最大长度（二进制中连续 1 的最长长度）。
函数需返回一个长度为 3 的数组（十进制整数），依次包含：交集结果、并集结果、最大连续可用信道长度。输入描述本题为核心代码模式，你需要实现函数 channelMaskStats(maskStrA, maskStrB)。参数：
maskStrA：为第一个掩码的字符串表示，仅包含合法的进制格式（无需处理非法输入），掩码值满足 \(0 \le mask \le 2^{64}-1\)，超出范围的输入不存在。
maskStrB：为第二个掩码的字符串表示，格式与取值范围同 maskStrA。
二进制字符串长度不超过 64 位，十六进制字符串长度不超过 16 位。连续可用信道长度计算规则：全 0 掩码返回 0，全 1 掩码返回 64。输出描述返回一个长度为 3 的数组（十进制整数），依次包含：交集结果、并集结果、最大连续可用信道长度。样例 1输入：
maskStrA = "0b1011", maskStrB = "0b1101"
"""


def main(maskA, maskB):
    # int(s, 0), 0自动匹配0x 0b
    ma = int(maskA, 0)
    mb = int(maskB, 0)

    # 交集， 按位与
    ans1 = ma & mb
    # 并集，按位或
    ans2 = ma | mb

    ans3 = 0
    tmp = ans2
    cur = 0
    for _ in range(64):
        # 用1按位与tmp， tmp最右边的是1，则信道可用， 更新当前最大值
        """
        1001
           1
        ______
           1
        右移之后继续比, 就是判断最后一位是否是1
        100
          1
        ____
          0
        """
        if tmp & 1:
            cur += 1
            ans3 = max(ans3, cur)
        # 否则，当前不可用，cur 置为0
        else:
            cur = 0
        # tmp右移一位
        tmp >>= 1

    return ans1, ans2, ans3


if __name__ == "__main__":
    maskA = "0b1011"
    maskB = "0b1101"

    res = main(maskA, maskB)
    print(res)  # output 9. 15 4
