"""
给定一个十进制大整数（最多100位），将其二进制表示中的所有位顺序全部反转，即最低位变最高位、次低位变成次高位，依次类推，然后返回反转后的十进制表示
输入描述：
参数num为一个十进制大整数的字符串形式，取值0-100^100-1,输入不带前导0，除非该数本身为0
输出描述
返回翻转后的十进制整数的字符串形式，结果不能带前导0

样例1
num = "1"
输出
"1"

"""

def main(s):

    b = bin(int(s))
    str_b = str(b)[2:]
    rever_s = str_b[::-1]
    res = int(rever_s,2)
    return res

res = main("10")
print(res)